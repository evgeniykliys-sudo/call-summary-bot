"""Синтезирует тестовую запись планёрки (3 голоса через Microsoft Edge TTS) с заранее
известными решениями и задачами — чтобы проверять выжимку не на глаз, а по списку.

    python scripts/make_test_meeting.py   →   scripts/test_meeting.mp3

Ожидаемый результат — в EXPECTED ниже (и в scripts/expected.md).
"""
import asyncio
from pathlib import Path

import edge_tts

OUT = Path(__file__).parent / "test_meeting.mp3"

# В Edge TTS всего два русских голоса — третьего участника отличаем высотой и темпом.
VOICES = {
    "Ольга": ("ru-RU-SvetlanaNeural", "+0Hz", "+0%"),
    "Дмитрий": ("ru-RU-DmitryNeural", "+0Hz", "+0%"),
    "Светлана": ("ru-RU-SvetlanaNeural", "+25Hz", "+12%"),
}

SCRIPT = [
    ("Ольга", "Всем привет. Сегодня решаем, как запускаем Телеграм-бота для записи в нашу стоматологию. Дмитрий, что по срокам?"),
    ("Дмитрий", "Основная часть готова: выбор услуги, даты и свободного времени работает. Думаю, до двадцатого октября можно запускаться."),
    ("Ольга", "Хорошо. Тогда фиксируем: запускаем бота до двадцатого октября."),
    ("Светлана", "А предоплату через бота будем брать? Многие клиники так делают, чтобы меньше было неявок."),
    ("Ольга", "Пока нет. Предоплату не берём, сначала посмотрим, как пойдёт. Но напоминания пациентам нужны обязательно."),
    ("Дмитрий", "Напоминание за день до визита я подключу до пятницы."),
    ("Светлана", "Мне тогда нужно подготовить тексты для меню бота: приветствие, описание услуг, контакты. Сделаю до среды."),
    ("Ольга", "Отлично. Цены на услуги я согласую с бухгалтерией до понедельника и перешлю Дмитрию."),
    ("Светлана", "По рекламе: предлагаю на первый месяц тридцать тысяч рублей, таргет на район клиники."),
    ("Ольга", "Согласна, бюджет на рекламу на первый месяц — тридцать тысяч."),
    ("Дмитрий", "Ещё вопрос: записывать к конкретному врачу или в любое свободное окно? От этого зависит логика расписания."),
    ("Ольга", "Хороший вопрос, сейчас не готова ответить. Обсудим на следующей встрече."),
    ("Ольга", "Всё, спасибо, на этом заканчиваем."),
]

EXPECTED = """# Ожидаемая выжимка тестовой планёрки

## Решения (3)
1. Запуск бота записи — до 20 октября.
2. Предоплату пока не берём; напоминания пациентам — обязательно.
3. Бюджет на рекламу на первый месяц — 30 000 ₽ (таргет на район клиники).

## Задачи (3)
| Задача | Ответственный | Срок |
|---|---|---|
| Подключить напоминание за день до визита | Дмитрий | до пятницы |
| Подготовить тексты для меню бота (приветствие, услуги, контакты) | Светлана | до среды |
| Согласовать цены на услуги с бухгалтерией и переслать Дмитрию | Ольга | до понедельника |

## Открытые вопросы (1)
- Запись к конкретному врачу или в любое свободное окно — обсудить на следующей встрече.
"""


async def main():
    parts = []
    for i, (speaker, text) in enumerate(SCRIPT):
        tmp = OUT.parent / f"_part{i:02d}.mp3"
        voice, pitch, rate = VOICES[speaker]
        await edge_tts.Communicate(text, voice, pitch=pitch, rate=rate).save(str(tmp))
        parts.append(tmp)
    # mp3 от edge-tts в одном формате — склейка кадров побайтово корректна
    OUT.write_bytes(b"".join(p.read_bytes() for p in parts))
    for p in parts:
        p.unlink()
    (OUT.parent / "expected.md").write_text(EXPECTED, encoding="utf-8")
    print(f"{OUT} ({OUT.stat().st_size // 1024} КБ, {len(SCRIPT)} реплик)")


if __name__ == "__main__":
    asyncio.run(main())
